#!/bin/bash
# Hyprland's part of provisioning: runs as root in the booted golden image right before the warm
# state is saved, after what every desktop image gets (images/shared/desktop.sh). Hyprland reads
# its configuration again when the file changes.
set -euo pipefail
install -d -o tester -g tester /home/tester/.config /home/tester/.config/hypr
# Hyprland 0.56 writes a Lua configuration when it finds none and then reads that one first;
# hyprctl keyword (desk display) works with this one only.
if grep -qs autogenerated /home/tester/.config/hypr/hyprland.lua; then
    rm /home/tester/.config/hypr/hyprland.lua
fi
# The keyboard layout desk types through; a still screen (no animations, no wallpaper of its own
# that moves); no update news. Hyprland itself never locks or blanks the screen.
cat > /home/tester/.config/hypr/hyprland.conf <<CONF
monitor = , preferred, auto, 1

input {
    kb_layout = $DESK_LAYOUT
}

animations {
    enabled = false
}

misc {
    disable_hyprland_logo = true
    disable_splash_rendering = true
    force_default_wallpaper = 0
}

ecosystem {
    no_update_news = true
    no_donation_nag = true
}

bind = SUPER, Return, exec, kitty
CONF
chown tester:tester /home/tester/.config/hypr/hyprland.conf
